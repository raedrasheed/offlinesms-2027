#!/usr/bin/env node
// Renders the starter sticker pack (scripts/stickers/simsim.mjs) to transparent
// WebP files in assets/stickers/simsim/ using headless Chromium (Playwright),
// and writes the pack manifest consumed by src/lib/stickers.generated.ts.
//
//   node scripts/stickers/build-stickers.mjs
//   (PLAYWRIGHT_BROWSERS_PATH / a local Chromium is required; output is committed)

import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { STICKERS } from './simsim.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const outDir = join(root, 'assets', 'stickers', 'simsim');
mkdirSync(outDir, { recursive: true });

const require = createRequire(import.meta.url);
let chromium;
try { ({ chromium } = require('playwright')); }
catch { ({ chromium } = require(process.env.PLAYWRIGHT_MODULE ?? 'playwright')); }

const SIZE = 384;
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const page = await browser.newPage();
await page.setContent('<html><body></body></html>');

const sizes = {};
for (const st of STICKERS) {
  const dataUrl = await page.evaluate(async ({ svg, size }) => {
    const img = new Image();
    img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
    await img.decode();
    const c = document.createElement('canvas');
    c.width = size; c.height = size;
    c.getContext('2d').drawImage(img, 0, 0, size, size);
    return c.toDataURL('image/webp', 0.82);
  }, { svg: st.svg, size: SIZE });
  const buf = Buffer.from(dataUrl.split(',')[1], 'base64');
  writeFileSync(join(outDir, `${st.id}.webp`), buf);
  writeFileSync(join(here, 'svg', `${st.id}.svg`), st.svg);
  sizes[st.id] = buf.length;
}
await browser.close();

const manifest = {
  id: 'simsim', version: 1, license: 'CC0-1.0', size: SIZE,
  stickers: STICKERS.map(s => ({ id: s.id, alt: s.alt, en: s.en, ar: s.ar })),
};
writeFileSync(join(outDir, 'pack.json'), JSON.stringify(manifest, null, 2) + '\n');
// Static require() map for Metro (images load only when a sticker renders).
const req = STICKERS.map(s => `    ${JSON.stringify(s.id)}: require('../../../assets/stickers/simsim/${s.id}.webp'),`).join('\n');
writeFileSync(join(root, 'src', 'components', 'chat', 'stickerSources.ts'),
`// GENERATED by scripts/stickers/build-stickers.mjs — do not edit by hand.
// Bundled sticker images by pack → sticker id. Metro resolves these at build
// time; React Native decodes an image only when a sticker is actually shown.
/* eslint-disable @typescript-eslint/no-var-requires */
export const STICKER_SOURCES: Record<string, Record<string, number>> = {
  simsim: {
${req}
  },
};
`);
const total = Object.values(sizes).reduce((a, b) => a + b, 0);
console.log(`stickers: ${STICKERS.length} → ${outDir} (${(total / 1024).toFixed(1)} KB total)`);
