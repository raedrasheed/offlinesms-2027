#!/usr/bin/env node
// Generates the composer emoji picker's data from Unicode CLDR sources:
//   src/lib/emojiData.ts      — categories, emoji, Unicode Emoji version (small)
//   src/lib/emojiKeywords.ts  — English + Arabic search keywords (loaded on first search)
//
// Inputs (pass the unpacked npm tarballs' paths; nothing is installed):
//   emojibase-data@16.0.3            (MIT)         en/data.json — order, groups, versions, en CLDR labels/tags
//   cldr-annotations-full@46.0.0     (Unicode-3.0) annotations/ar/annotations.json
//   cldr-annotations-derived-full@46.0.0 (Unicode-3.0) annotationsDerived/ar/annotations.json (flags, sequences)
//
//   node scripts/build-emoji-data.mjs <emojibase-data dir> <cldr-annotations-full dir> <cldr-annotations-derived-full dir>
//
// Skin-tone variants are left out (base emoji only) to keep the bundle small.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const [emojibaseDir, cldrDir, cldrDerivedDir] = process.argv.slice(2);
if (!emojibaseDir || !cldrDir || !cldrDerivedDir) {
  console.error('usage: build-emoji-data.mjs <emojibase-data> <cldr-annotations-full> <cldr-annotations-derived-full>');
  process.exit(2);
}
const here = dirname(fileURLToPath(import.meta.url));
const out = (f) => join(here, '..', 'src', 'lib', f);

const data = JSON.parse(readFileSync(join(emojibaseDir, 'en', 'data.json'), 'utf8'));
const arBase = JSON.parse(readFileSync(join(cldrDir, 'annotations', 'ar', 'annotations.json'), 'utf8')).annotations.annotations;
const arDerived = JSON.parse(readFileSync(join(cldrDerivedDir, 'annotationsDerived', 'ar', 'annotations.json'), 'utf8')).annotationsDerived.annotations;

// emojibase group id → picker category (group 2 = skin-tone/hair components: skipped).
const GROUPS = [
  [0, 'smileys', '😀'], [1, 'people', '👋'], [3, 'nature', '🐻'], [4, 'food', '🍔'],
  [5, 'travel', '🚗'], [6, 'activities', '⚽'], [7, 'objects', '💡'], [8, 'symbols', '❤️'], [9, 'flags', '🏳️'],
];

const versions = [...new Set(data.map(e => e.version))].sort((a, b) => a - b);
const vcode = (v) => versions.indexOf(v).toString(36);
if (versions.length > 36) throw new Error('too many versions for one-char codes');

const strip = (s) => s.replace(/️/g, '');
function arWords(e) {
  const a = arBase[e.emoji] ?? arBase[strip(e.emoji)] ?? arDerived[e.emoji] ?? arDerived[strip(e.emoji)];
  if (!a) return [];
  return [...new Set([...(a.tts ?? []), ...(a.default ?? [])])].slice(0, 5);
}

const groups = [];
const kw = [];
let missingAr = 0;
for (const [id, key, icon] of GROUPS) {
  const items = data.filter(e => e.group === id).sort((a, b) => a.order - b.order);
  groups.push({ key, icon, chars: items.map(e => e.emoji).join('|'), versions: items.map(e => vcode(e.version)).join('') });
  for (const e of items) {
    const en = [...new Set([e.label, ...(e.tags ?? [])])].slice(0, 6).join(' ');
    const ar = arWords(e);
    if (ar.length === 0) missingAr++;
    kw.push(`${e.emoji}\t${en}\t${ar.join(' ')}`);
  }
}

const header = (what) => `// GENERATED by scripts/build-emoji-data.mjs — do not edit by hand.
// ${what}
// Sources: emojibase-data 16.0.3 (MIT), Unicode CLDR 46 annotations (Unicode License v3).
// See THIRD_PARTY_NOTICES.md.
`;

writeFileSync(out('emojiData.ts'), `${header('Emoji picker categories (base emoji, no skin-tone variants).')}
/** Unicode Emoji versions; \`versions\` below holds one base-36 index per emoji. */
export const EMOJI_VERSIONS: number[] = ${JSON.stringify(versions)};

export interface EmojiGroupData { key: string; icon: string; chars: string; versions: string }

export const EMOJI_GROUP_DATA: EmojiGroupData[] = ${JSON.stringify(groups, null, 1)};
`);

writeFileSync(out('emojiKeywords.ts'), `${header('Search keywords, one line per emoji: "<emoji>\\t<english>\\t<arabic>".')}
export const EMOJI_KEYWORDS = ${JSON.stringify(kw.join('\n'))};
`);

console.log(`emoji: ${kw.length} in ${groups.length} groups, versions ${versions.join(',')}; no Arabic keywords for ${missingAr}`);
